import { test as base, expect } from '@playwright/test';
const test = base.extend<{ errors: string[] }>({ errors: [async ({ page }, use) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  await use(errors); expect(errors).toEqual([]);
}, { auto: true }] });
async function start(page: import('@playwright/test').Page, kind: 'ER' | 'class') {
  await page.goto('/');
  await page.getByText('New diagram', { exact: true }).click();
  await page.getByRole('button', { name: `New ${kind} diagram`, exact: true }).click();
  await expect(page.getByLabel('Diagram Mermaid source')).toBeVisible();
}
test('ER attributes, relationship semantics, folding and reload', async ({ page }) => {
  await start(page, 'ER');
  await page.getByRole('button', { name: 'Entity CUSTOMER', exact: true }).locator('.st-card-head').click();
  await page.getByLabel('Entity name').fill('Customers');
  await page.getByRole('button', { name: '+ Attribute', exact: true }).click();
  await page.getByLabel('Attribute name').fill('account_id');
  await page.getByLabel('FK', { exact: true }).check();
  await page.getByLabel('Attribute comment').fill('Account reference');
  await expect(page.getByLabel('Diagram Mermaid source')).toHaveValue(/account_id FK "Account reference"/);
  await page.getByRole('button', { name: 'Relationship places', exact: true }).click();
  await page.getByLabel('Target cardinality').selectOption('one-or-more');
  await page.getByLabel('Identifying relationship').uncheck();
  await expect(page.getByLabel('Diagram Mermaid source')).toHaveValue(/\|\|\.\.\|\{/);
  await page.getByRole('button', { name: 'Entity Customers', exact: true }).locator('.st-card-head').click();
  await page.getByRole('region', { name: 'Selected diagram element' }).getByRole('button', { name: 'Fold details', exact: true }).click();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document?.diagram?.entities.find((e: { id: string }) => e.id === 'CUSTOMER')?.collapsed)).toBe(true);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Entity Customers', exact: true })).toBeVisible();
  await expect(page.getByLabel('Diagram Mermaid source')).toHaveValue(/account_id/);
  await page.getByLabel('Diagram Mermaid source').fill('erDiagram\nunsupported !!!');
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Entity Customers', exact: true })).toBeVisible();
});
