test('class namespace creation, Tidy and manual placement survive reload', async ({ page }) => {
  await start(page, 'class');
  await page.getByRole('button', { name: '+ Namespace', exact: true }).click();
  await page.getByLabel('Namespace name', { exact: true }).fill('Utilities');
  await page.getByRole('button', { name: 'Tidy', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  const header = page.getByRole('button', { name: 'Class Animal', exact: true }).locator('.st-card-head');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document?.diagram?.namespaces.some((n: { label: string }) => n.label === 'Utilities'))).toBe(true);
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document.diagram.classes.find((c: { id: string }) => c.id === 'Animal').position);
  await header.click({ trial: true });
  const bounds = await header.boundingBox();
  expect(bounds).not.toBeNull();
  if (!bounds) return;
  await page.mouse.move(bounds.x + 40, bounds.y + 15);
  await page.mouse.down();
  await page.mouse.move(bounds.x + 120, bounds.y + 65, { steps: 8 });
  await page.mouse.up();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document?.diagram?.namespaces.some((n: { label: string }) => n.label === 'Utilities'))).toBe(true);
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document.diagram.classes.find((c: { id: string }) => c.id === 'Animal').position)).not.toEqual(before);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document.diagram.classes.find((c: { id: string }) => c.id === 'Animal').position);
  await page.reload();
  await expect(page.getByLabel('Diagram Mermaid source')).toBeVisible();
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('merfolk.diagram') ?? '{}').document.diagram.classes.find((c: { id: string }) => c.id === 'Animal').position);
  expect(restored).toEqual(saved);
});
