import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { parseMermaid, mergeDiagram } from '../src/mermaid/io.ts';
const dom = new JSDOM('', { url: 'https://merfolk.test/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage });
const { useDiagram } = await import('../src/store.ts');
const { currentDocument, loadDocument } = await import('../src/persist.ts');
const graph = (source: string) => { const p = parseMermaid(source); if (!p.ok) throw new Error(p.error); return p.diagram; };
const first = graph('flowchart TD\nA -->|old| B');
const inserted = mergeDiagram(graph('flowchart TD\nC -->|new| D\nA -->|old| B'), first);
assert.equal(new Set(inserted.edges.map((e) => e.id)).size, 2, 'inserted edges must not reuse a retained edge ID');
assert.equal(inserted.edges.find((e) => e.label === 'old')?.id, first.edges[0].id);
useDiagram.getState().load(inserted);
useDiagram.getState().removeEdge(inserted.edges[0].id);
assert.deepEqual(useDiagram.getState().diagram.kind === 'flowchart' && useDiagram.getState().exportMermaid().includes('old'), true);
const parallel = { ...graph('flowchart TD\nA -->|first| B\nA -->|second| B'), edges: [
  { id: 'first', source: 'A', target: 'B', label: 'first', style: { stroke: 'red' }, order: 2 },
  { id: 'second', source: 'A', target: 'B', label: 'second', style: { stroke: 'blue' }, order: 3 },
] };
const reordered = mergeDiagram(graph('flowchart TD\nA -->|second| B\nA -->|first changed| B'), parallel);
assert.deepEqual(reordered.edges.map((e) => [e.id, e.style?.stroke, e.order]), [['second', 'blue', 3], ['first', 'red', 2]]);
const repeated = mergeDiagram(graph('flowchart TD\nA --> B\nA --> B\nA --> B'), graph('flowchart TD\nA --> B\nA --> B'));
assert.equal(new Set(repeated.edges.map((edge) => edge.id)).size, 3, 'identical parallel occurrences remain independent');
useDiagram.getState().load(parallel);
const history = useDiagram.getState().history;
useDiagram.getState().syncMermaid(useDiagram.getState().exportMermaid() + '\n%% comment');
assert.equal(useDiagram.getState().history, history);
useDiagram.getState().setSelection(['A'], ['first']);
useDiagram.getState().setHighlight({ kind: 'edge', id: 'first' });
const saved = currentDocument();
if (saved.diagram.kind !== 'flowchart') throw new Error('Expected flowchart');
loadDocument({ ...saved, diagram: { ...saved.diagram, nodes: saved.diagram.nodes.map((n) => n.id === 'B' ? { ...n, pageIds: ['p'] } : n) }, pages: [{ id: 'p', title: 'Notes', body: '', updatedAt: Date.now() }] }, true);
assert.deepEqual(useDiagram.getState().selectedNodeIds, ['A']);
assert.deepEqual(useDiagram.getState().selectedEdgeIds, ['first']);
assert.deepEqual(useDiagram.getState().highlight, { kind: 'edge', id: 'first' });
loadDocument({ ...saved, diagram: { ...saved.diagram, nodes: saved.diagram.nodes.filter((n) => n.id !== 'A'), edges: [] } }, true);
assert.deepEqual(useDiagram.getState().selectedNodeIds, []);
assert.deepEqual(useDiagram.getState().selectedEdgeIds, []);
assert.equal(useDiagram.getState().highlight, null);
const baseline = useDiagram.getState().diagram;
if (baseline.kind !== 'flowchart') throw new Error('Expected flowchart');
const edit = (label: string) => ({ ...baseline, nodes: baseline.nodes.map((node) => ({ ...node, label })) });
const beforeEdits = useDiagram.getState().history.length;
useDiagram.getState().commitSource(edit('first edit'));
useDiagram.getState().commitSource(edit('second edit'));
assert.equal(useDiagram.getState().history.length, beforeEdits + 1);
useDiagram.getState().undo();
assert.equal(useDiagram.getState().diagram, baseline, 'one undo restores the diagram before a source editing run');
useDiagram.getState().commitSource(edit('after undo'));
assert.equal(useDiagram.getState().history.length, beforeEdits + 1, 'editing after undo starts a new undo step');
const nativeEdit = edit('native edit');
useDiagram.getState().setDiagram(nativeEdit);
const beforeNewRun = useDiagram.getState().history.length;
useDiagram.getState().commitSource(edit('after native edit'));
assert.equal(useDiagram.getState().history.length, beforeNewRun + 1, 'native edits end source coalescing');
useDiagram.getState().undo();
assert.equal(useDiagram.getState().diagram, nativeEdit);
console.log('PASS: distinct flowchart edge identity, remote selection preservation and source undo boundaries');
dom.window.close();
