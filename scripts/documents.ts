import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { sampleSequence, emitSequence, parseSequence } from '../src/sequence/io.ts';
const dom = new JSDOM('', { url: 'https://merfolk.test/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage });
const { useDiagram } = await import('../src/store.ts');
const { currentDocument, decodeDocument, loadDocument, readDocument, write } = await import('../src/persist.ts');
const sequenceOf = () => { const diagram = useDiagram.getState().diagram; if (diagram.kind !== 'sequence') throw new Error('Expected sequence'); return diagram; };
const legacy = { nodes: [{ id: 'a', label: 'API', shape: 'rect', parentId: null, collapsed: false, position: { x: 0, y: 0 }, pageId: 'p' }], edges: [], pages: [{ id: 'p', title: 'Notes', body: 'Preserved', updatedAt: 1 }] };
for (const input of [legacy, { version: 1, diagram: legacy }, { version: 2, diagram: legacy }]) {
  const decoded = decodeDocument(input);
  assert.equal(decoded.diagram.kind, 'flowchart');
  if (decoded.diagram.kind === 'flowchart') assert.deepEqual(decoded.diagram.nodes[0].pageIds, ['p']);
  assert.equal(decoded.pages[0].body, 'Preserved');
}
assert.throws(() => decodeDocument({ version: 99, diagram: legacy }), /version/);
loadDocument(decodeDocument(legacy));
useDiagram.getState().setDiagram(sampleSequence());
const id = useDiagram.getState().openPage('API');
assert.ok(id);
assert.ok(sequenceOf().participants.find((p) => p.id === 'API')?.pageIds?.includes(id));
useDiagram.getState().updatePage(id, { body: '{{diagram}}' });
const saved = currentDocument();
write(saved);
assert.equal(JSON.parse(localStorage.getItem('merfolk.diagram')!).version, 3);
assert.deepEqual(readDocument(), saved);
useDiagram.getState().load({ nodes: [], edges: [] });
loadDocument(saved);
assert.deepEqual(currentDocument(), saved);
let notifications = 0;
const stop = useDiagram.subscribe(() => notifications++);
loadDocument(saved, true);
assert.equal(notifications, 0, 'identical remote save must not echo');
stop();
const before = useDiagram.getState().diagram;
assert.equal(before.kind, 'sequence');
if (before.kind !== 'sequence') throw new Error('Expected sequence');
useDiagram.getState().setDiagram({ ...before, participants: [...before.participants].reverse() });
useDiagram.getState().undo();
assert.deepEqual(useDiagram.getState().diagram, before);
const priorHistory = useDiagram.getState().history;
loadDocument({ ...saved, pages: saved.pages.map((p) => p.id === id ? { ...p, body: 'remote', updatedAt: Date.now() + 1 } : p) }, true);
assert.equal(useDiagram.getState().history, priorHistory, 'page-only remote change retains diagram undo');
const bad = useDiagram.getState().syncMermaid('sequenceDiagram\nunsupported junk');
assert.equal(bad.ok, false);
assert.deepEqual(useDiagram.getState().diagram, before);
const source = emitSequence(before).text;
assert.equal(parseSequence(source).ok, true);
useDiagram.getState().setDiagram({kind:'flowchart',nodes:[],edges:[]});
useDiagram.getState().undo();
assert.deepEqual(useDiagram.getState().diagram, before, 'kind switching is undoable');
useDiagram.getState().deletePage(id);
useDiagram.getState().undo();
assert.ok(!sequenceOf().participants.some((p) => p.pageIds?.includes(id)));
useDiagram.getState().setDiagram(sampleSequence());
loadDocument(decodeDocument(legacy), true);
assert.equal(useDiagram.getState().diagram.kind, 'flowchart');
assert.equal(useDiagram.getState().history.length, 0, 'remote kind switches reset incompatible history');
assert.throws(() => decodeDocument({ diagram: { kind: 'unknown', nodes: [], edges: [] } }), /kind/);
const { sampleStructural, emitStructural } = await import('../src/structural/io.ts');
for (const kind of ['er', 'class'] as const) {
  const diagram = sampleStructural(kind);
  useDiagram.getState().setDiagram(diagram);
  const entity = diagram.kind === 'er' ? diagram.entities[0] : diagram.classes[0];
  const pageId = useDiagram.getState().openPage(entity.id);
  assert.ok(pageId);
  useDiagram.getState().updatePage(pageId, { body: 'Shared structural notes' });
  const document = currentDocument();
  write(document);
  assert.deepEqual(readDocument(), document);
  loadDocument(document);
  assert.equal(useDiagram.getState().diagram.kind, kind);
  const beforeGraphCommand = useDiagram.getState().diagram;
  useDiagram.getState().removeNode(entity.id);
  assert.equal(useDiagram.getState().diagram, beforeGraphCommand, 'graph command does not mutate another diagram kind');
  assert.equal(useDiagram.getState().syncMermaid(emitStructural(diagram).text).ok, true);
  const { entitiesOf } = await import('../src/entities.ts');
  assert.ok(entitiesOf(useDiagram.getState().diagram).find((e) => e.id === entity.id)?.pageIds?.includes(pageId), 'source sync retains omitted page metadata');
  assert.ok(useDiagram.getState().pages.some((p) => p.id === pageId && p.body === 'Shared structural notes'));
  useDiagram.getState().setDiagram(sampleSequence());
  useDiagram.getState().undo();
  assert.equal(useDiagram.getState().diagram.kind, kind, 'undo restores structural kind');
}
console.log('PASS: document migration, sequence persistence, history, wiki pages and remote no-op');
dom.window.close();
